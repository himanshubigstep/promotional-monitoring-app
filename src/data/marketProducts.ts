export const getMarketProducts = (market: "PL" | "CZ") =>
  market === "PL" ? [...plProducts] : [...czProducts];

export const upsertProductInMarket = (
  market: "PL" | "CZ",
  product: Product,
  currentList: Product[] = getMarketProducts(market),
) => {
  const isDuplicate = currentList.some(
    (item) =>
      item.id === product.id ||
      (item.name.toLowerCase() === product.name.toLowerCase() &&
        item.brand.toLowerCase() === product.brand.toLowerCase()),
  );

  const nextList = isDuplicate ? currentList : [product, ...currentList];

  if (market === "PL") {
    plProducts = nextList;
  } else {
    czProducts = nextList;
  }

  return nextList;
};

